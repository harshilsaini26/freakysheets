def div(a, b):
    if a is None or b is None or b == 0:
        return None
    return a / b


class Ctx:
    """Accessors over one company's statements for a given analysis year."""

    def __init__(self, data, year):
        self.st = data["statements"]
        self.years = data["years"]
        self.y = year
        idx = self.years.index(year)
        self.prev = self.years[idx - 1] if idx > 0 else None
        self.used_ending_balance = False

    def get(self, item, y=None):
        y = self.y if y is None else y
        for sect in self.st.values():
            if item in sect:
                v = sect[item].get(y)
                if v is None:
                    v = sect[item].get(str(y))  # JSON round-trip safety
                return v
        return None

    def p(self, item):
        return self.get(item, self.prev) if self.prev is not None else None

    def avg(self, item):
        cur, prev = self.get(item), self.p(item)
        if cur is None:
            return None
        if prev is None:
            self.used_ending_balance = True
            return cur
        return (cur + prev) / 2

    def pos_avg(self, item):
        """Average that must be positive (equity can be negative after buybacks)."""
        v = self.avg(item)
        return v if v is not None and v > 0 else None


def neg(v):
    return -v if v is not None else None


