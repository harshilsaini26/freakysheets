def _yoy(c, item):
    cur, prev = c.get(item), c.p(item)
    if cur is None or prev is None or prev == 0:
        return None
    return (cur - prev) / abs(prev)


def _ccc(c):
    dso = div(365, div(c.get("revenue"), c.avg("receivables")))
    dio = div(365, div(c.get("cost_of_revenue"), c.avg("inventory"))) or 0
    dpo = div(365, div(c.get("cost_of_revenue"), c.avg("accounts_payable")))
    if dso is None or dpo is None:
        return None
    return dso + dio - dpo


def _sgr(c):
    roe = div(c.get("net_income"), c.pos_avg("equity"))
    payout = div(c.get("dividends_paid"), c.get("net_income"))
    if roe is None or payout is None:
        return None
    return roe * (1 - payout)


