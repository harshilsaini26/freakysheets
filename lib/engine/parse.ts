// Turn a spreadsheet (CSV or Excel rows) into statements the engine understands.
// It accepts the official template (rows start with an item key such as
// "revenue - Revenue") and ordinary statements copied from a 10-K or annual
// report, where rows carry labels like "Net sales" or "Total current assets".

import { CONCEPTS } from "./core";
import type { Section, Statements, Template } from "./types";

export type Cell = string | number | boolean | Date | null | undefined;

export interface ParsedRow {
  rowIndex: number;
  label: string;
  values: Record<string, number>; // year -> value (already scaled)
  key: string | null; // matched line item, or null if not recognized
  how: "key" | "label" | "manual" | null;
}

export interface ParseResult {
  years: number[];
  rows: ParsedRow[];
  warnings: string[];
}

