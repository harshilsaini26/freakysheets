// Items that are usually shown as positive numbers even when they are cash outflows.
const OUTFLOWS = new Set(["capex", "dividends_paid", "buybacks"]);

export function norm(s: string) {
  return s
    .toLowerCase()
    .replace(/&/g, " and ")
    .replace(/\(.*?\)/g, " ")
    .replace(/[^a-z0-9 ]+/g, " ")
    .replace(/\s+/g, " ")
    .trim();
}

export function yearOf(cell: Cell): number | null {
  if (cell instanceof Date) return cell.getUTCFullYear();
  if (typeof cell === "number") return cell >= 1990 && cell <= 2100 && Number.isInteger(cell) ? cell : null;
  if (typeof cell !== "string") return null;
  const m = cell.match(/(?:^|\D)(19[9]\d|20\d\d)(?:\D|$)/);
  return m ? Number(m[1]) : null;
}

export function toNumber(cell: Cell): number | null {
  if (typeof cell === "number") return Number.isFinite(cell) ? cell : null;
  if (typeof cell !== "string") return null;
  let s = cell.trim();
  if (!s || /^[-–—]+$/.test(s) || /^n\/?a$/i.test(s)) return null;
  let neg = false;
  if (/^\(.*\)$/.test(s)) {
    neg = true;
    s = s.slice(1, -1);
  }
  s = s.replace(/[$€£¥,\s]/g, "");
  if (s.startsWith("-") || s.startsWith("−")) {
    neg = !neg;
    s = s.slice(1);
  }
  if (!/^\d*\.?\d+(e[+-]?\d+)?$/i.test(s)) return null;
  const v = Number(s);
  return neg ? -v : v;
}

export function itemsFor(template: Template) {
  return CONCEPTS[template];
}

function matchLabel(label: string, template: Template, taken: Set<string>): [string | null, ParsedRow["how"]] {
  const keys = new Set(CONCEPTS[template].map((c) => c.key));
  // 1) template format: "revenue - Revenue" or just "revenue"
  const first = label.trim().split(/\s+/)[0];
  if (keys.has(first)) return [first, "key"];
  // 2) label synonyms
  const n = norm(label);
  const variants = [n, n.replace(/^total /, ""), n.replace(/ net$/, ""), n.replace(/^net /, "")];
  for (const v of variants) {
    for (const [key, syns] of Object.entries(SYNONYMS)) {
      if (!keys.has(key) || taken.has(key)) continue;
      if (syns.includes(v)) return [key, "label"];
    }
  }
  return [null, null];
}

/** Parse rows from any sheet. `scale` multiplies every value (e.g. 1e6 if the file is in millions). */
export function parseRows(rows: Cell[][], template: Template, scale = 1): ParseResult {
  const warnings: string[] = [];
  // Find the header row: the first row with at least two year-like cells.
  let headerIdx = -1;
  let yearCols: [number, number][] = [];
  for (let i = 0; i < Math.min(rows.length, 40); i++) {
    const cols = (rows[i] ?? [])
      .map((c, j) => [j, yearOf(c)] as [number, number | null])
      .filter((x): x is [number, number] => x[1] !== null && x[0] > 0);
    if (cols.length >= 2) {
      headerIdx = i;
      yearCols = cols;
      break;
    }
  }
  if (headerIdx < 0) {
    return { years: [], rows: [], warnings: ["Could not find a header row with fiscal years (e.g. 2021, 2022...)."] };
  }
  // Keep one column per year (first occurrence).
  const seen = new Set<number>();
  yearCols = yearCols.filter(([, y]) => (seen.has(y) ? false : (seen.add(y), true)));
  const years = yearCols.map(([, y]) => y).sort((a, b) => a - b);

  const taken = new Set<string>();
  const out: ParsedRow[] = [];
  for (let i = headerIdx + 1; i < rows.length; i++) {
    const row = rows[i] ?? [];
    const labelCell = row.slice(0, yearCols[0][0]).find((c) => typeof c === "string" && c.trim());
    if (typeof labelCell !== "string") continue;
    const values: Record<string, number> = {};
    for (const [j, y] of yearCols) {
      const v = toNumber(row[j]);
      if (v !== null) values[String(y)] = v * (keyIsPerShare(labelCell) ? 1 : scale);
    }
    if (!Object.keys(values).length) continue;
    const [key, how] = matchLabel(labelCell, template, taken);
    if (key) taken.add(key);
    out.push({ rowIndex: i, label: labelCell.trim(), values, key, how });
  }
  if (years.length < 2) warnings.push("At least two fiscal years are needed for growth rates and averages.");
  if (years.length < 3) warnings.push("Three or more years are needed for forecasts and trend charts.");
  return { years, rows: out, warnings };
}

function keyIsPerShare(label: string) {
  const n = norm(label);
  return n.startsWith("eps diluted") || n.includes("per share") || n === "diluted eps" || n === "diluted";
}

/** Build statements from the (possibly user-edited) row mapping. */
export function toStatements(parsed: ParseResult, template: Template): Statements {
  const st: Statements = { income: {}, balance: {}, cashflow: {} };
  const defs = new Map(CONCEPTS[template].map((c) => [c.key, c.statement as Section]));
  const used = new Set<string>();
  for (const r of parsed.rows) {
    if (!r.key || used.has(r.key) || !defs.has(r.key)) continue;
    used.add(r.key);
    const values: Record<string, number> = {};
    for (const [y, v] of Object.entries(r.values)) values[y] = OUTFLOWS.has(r.key) ? Math.abs(v) : v;
    st[defs.get(r.key)!][r.key] = values;
  }
  return st;
}

export function parseCsvText(text: string): Promise<Cell[][]> {
  return import("papaparse").then(({ default: Papa }) => {
    const res = Papa.parse<string[]>(text.trim(), { skipEmptyLines: true });
    return res.data as Cell[][];
  });
}

/** Spot a units note such as "(in millions)" or "USD $ in Thousands" near the top of the file. */
export function detectScale(rows: Cell[][]): number {
  for (const row of rows.slice(0, 8)) {
    for (const c of row ?? []) {
      if (typeof c !== "string") continue;
      const s = c.toLowerCase();
      if (/\bin billions\b/.test(s)) return 1e9;
      if (/\bin millions\b/.test(s)) return 1e6;
      if (/\bin thousands\b/.test(s)) return 1e3;
    }
  }
  return 1;
}
